CREATE TABLE IF NOT EXISTS profit_transactions (
    id          TEXT PRIMARY KEY,
    tx_date     TEXT NOT NULL CHECK (
        length(tx_date) = 10 AND
        tx_date GLOB '[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]' AND
        date(tx_date, '+0 days') = tx_date AND substr(tx_date, 1, 4) >= '0001'
