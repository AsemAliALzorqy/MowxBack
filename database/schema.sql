-- The aggregate excludes deleted lines. A transaction with zero active lines
-- is retained in storage/audit history but absent from live ledgers and reports.
CREATE VIEW IF NOT EXISTS v_profit_transaction_totals AS
SELECT
    pt.id,
    pt.tx_date,
    COUNT(pl.id) AS line_count,
    SUM(pl.quantity_micros) AS quantity_micros,
    SUM(pl.amount_milli) AS amount_milli,
    CASE WHEN COUNT(pl.id) = 1 THEN MIN(pl.item_name) ELSE 'حركة أرباح أصناف' END AS display_name
FROM profit_transactions AS pt
JOIN profit_lines AS pl
  ON pl.transaction_id = pt.id AND pl.deleted_at IS NULL
WHERE pt.deleted_at IS NULL
GROUP BY pt.id, pt.tx_date
HAVING COUNT(pl.id) > 0;

-- A single row per profit movement, expense, or withdrawal. Withdrawals are
-- kept as a separate type and are added to expenses exactly once in totals.
CREATE VIEW IF NOT EXISTS v_all_transactions AS
SELECT
    'profit' AS type,
    p.id AS id,
    p.tx_date AS tx_date,
    p.display_name AS name,
    p.line_count AS line_count,
    p.quantity_micros AS quantity_micros,
    p.amount_milli AS amount_milli,
    '' AS description,
    '' AS notes,
    NULL AS category_id,
    NULL AS worker_id
FROM v_profit_transaction_totals AS p
UNION ALL
SELECT
    'expense', e.id, e.tx_date, e.category_name_snapshot, 0, 0,
    e.amount_milli, e.description, e.notes, e.category_id, NULL
FROM expenses AS e
WHERE e.deleted_at IS NULL
UNION ALL
SELECT
    'withdrawal', w.id, w.tx_date, w.worker_name_snapshot, 0, 0,
    w.amount_milli, '', w.notes, NULL, w.worker_id
FROM withdrawals AS w
WHERE w.deleted_at IS NULL;

CREATE VIEW IF NOT EXISTS v_daily_totals AS
SELECT
    tx_date,
    SUM(CASE WHEN type = 'profit' THEN amount_milli ELSE 0 END) AS profit_milli,
    SUM(CASE WHEN type = 'profit' THEN quantity_micros ELSE 0 END) AS profit_quantity_micros,
    SUM(CASE WHEN type = 'expense' THEN amount_milli ELSE 0 END) AS expense_milli,
    SUM(CASE WHEN type = 'withdrawal' THEN amount_milli ELSE 0 END) AS withdrawal_milli,
    SUM(CASE WHEN type IN ('expense', 'withdrawal') THEN amount_milli ELSE 0 END) AS total_expense_milli,
    SUM(CASE WHEN type = 'profit' THEN amount_milli ELSE -amount_milli END) AS net_milli
FROM v_all_transactions
GROUP BY tx_date;

CREATE VIEW IF NOT EXISTS v_profit_by_item AS
SELECT
    pt.tx_date,
    pl.item_name,
    SUM(pl.quantity_micros) AS quantity_micros,
    SUM(pl.amount_milli) AS amount_milli,
    COUNT(pl.id) AS line_count
FROM profit_transactions AS pt
JOIN profit_lines AS pl
  ON pl.transaction_id = pt.id AND pl.deleted_at IS NULL
WHERE pt.deleted_at IS NULL
GROUP BY pt.tx_date, pl.item_name;

CREATE VIEW IF NOT EXISTS v_expense_by_category AS
SELECT
    tx_date,
    category_id,
    category_name_snapshot,
    SUM(amount_milli) AS amount_milli,
    COUNT(id) AS operation_count
FROM expenses
WHERE deleted_at IS NULL
GROUP BY tx_date, category_id, category_name_snapshot;

CREATE VIEW IF NOT EXISTS v_withdrawal_by_worker AS
SELECT
    tx_date,
    worker_id,
    worker_name_snapshot,
    SUM(amount_milli) AS amount_milli,
    COUNT(id) AS operation_count
FROM withdrawals
WHERE deleted_at IS NULL
GROUP BY tx_date, worker_id, worker_name_snapshot;

