'use strict';

// Renderer-side adapter only. All persistent reads/writes are explicit IPC
// calls to Electron Main; this file intentionally has no LocalStorage path.
const Store = Object.freeze({
  load: () => window.mowx.getSnapshot(),
  report: (fromDate, toDate) => window.mowx.getReport({ fromDate, toDate }),
  reportOptions: () => window.mowx.getReportOptions(),
  customReport: (payload) => window.mowx.getCustomReportData(payload),
  exportReportPdf: (payload) => window.mowx.exportCustomReportPdf(payload),
  auditLog: (payload) => window.mowx.getAuditLog(payload),
  logApplicationError: (payload) => window.mowx.recordApplicationError(payload),
  diagnosticLog: (payload) => window.mowx.recordDiagnosticLog(payload),
  diagnosticStatus: () => window.mowx.getDiagnosticStatus(),
  openDiagnosticFolder: () => window.mowx.openDiagnosticFolder(),
  exportDiagnosticLogs: () => window.mowx.exportDiagnosticLogs(),
  setDiagnosticRetention: (payload) => window.mowx.setDiagnosticRetention(payload),
  telegramStatus: () => window.mowx.getTelegramStatus(),
  verifyTelegramToken: (payload) => window.mowx.verifyTelegramToken(payload),
  saveTelegramToken: (payload) => window.mowx.saveTelegramToken(payload),
  setTelegramEnabled: (payload) => window.mowx.setTelegramEnabled(payload),
  disconnectTelegram: () => window.mowx.disconnectTelegram(),
  saveTelegramBusinessName: (payload) => window.mowx.saveTelegramBusinessName(payload),
  createTelegramLink: (payload) => window.mowx.createTelegramLink(payload),
  copyTelegramLink: (payload) => window.mowx.copyTelegramLink(payload),
  showTelegramQr: (payload) => window.mowx.showTelegramQr(payload),
  openTelegramWhatsApp: (payload) => window.mowx.openTelegramWhatsApp(payload),
  unlinkTelegramWorker: (payload) => window.mowx.unlinkTelegramWorker(payload),
  sendTelegramTestMessage: (payload) => window.mowx.sendTelegramTestMessage(payload),
  retryTelegramNotification: (payload) => window.mowx.retryTelegramNotification(payload),
  onTelegramLinkChanged: (callback) => window.mowx.onTelegramLinkChanged(callback),
  saveProfit: (payload) => window.mowx.createProfitMovement(payload),
  updateProfitLine: (payload) => window.mowx.updateProfitLine(payload),
  deleteProfitLine: (payload) => window.mowx.deleteProfitLine(payload),
  updateProfitDate: (payload) => window.mowx.updateProfitDate(payload),
  deleteProfit: (payload) => window.mowx.deleteProfitMovement(payload),
  createExpense: (payload) => window.mowx.createExpense(payload),
  updateExpense: (payload) => window.mowx.updateExpense(payload),
  deleteExpense: (payload) => window.mowx.deleteExpense(payload),
  createWithdrawal: (payload) => window.mowx.createWithdrawal(payload),
  updateWithdrawal: (payload) => window.mowx.updateWithdrawal(payload),
  deleteWithdrawal: (payload) => window.mowx.deleteWithdrawal(payload),
  saveCatalog: (payload) => window.mowx.saveCatalogEntry(payload),
  setCatalogActive: (payload) => window.mowx.setCatalogActive(payload),
  setCurrency: (payload) => window.mowx.setCurrency(payload),
  searchNames: (query) => window.mowx.searchNameSuggestions(query),
});
